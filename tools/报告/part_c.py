    R.numbered("（2）无感刷新。",
               "实时监测每 15 秒轮询一次，一旦有新情报入库即弹出提示并热刷新相关区域，"
               "用户无需手动刷新页面。")
    R.numbered("（3）主题自适应。",
               "全部配色通过 CSS 变量定义，深色与浅色主题共用同一份结构，"
               "切换时无需重新渲染，代码块等宽显示在两种主题下都保持清晰。")
