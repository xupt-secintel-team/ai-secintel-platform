    R.h2("10.1 多智能体红蓝自博弈决策机制")
    R.rich([("解决的问题：", {'bold': True}),
            ('单一视角的安全判断容易乐观。决策智能体给出的优先级与动作清单，'
             '往往存在「看起来合理但经不起追问」的漏洞——'
             '例如有公开 POC 却只给 24 小时评估、'
             'CVSS 极高却未按最高优先级处理。', {})])
    R.rich([("创新做法：", {'bold': True}),
            ('引入立场相反的质疑智能体，站在攻击者视角对决策提出五类系统性质疑，'
             '蓝方逐条抗辩，最终收敛出更稳健的决策。'
             '质疑命中则修正决策（升档、补充动作、标注残余风险），'
             '未命中则标注「已通过对抗审视」。', {})])
    R.rich([("实现要点：", {'bold': True}),
            ('全部规则由结构化信号驱动，不依赖大模型推理，'
             '因此在无 API Key 环境下同样可完整运行，且每次运行结果完全一致，'
             '便于答辩现场复现。', {})])
    R.callout(
        "价值",
        "该机制把「可能被攻击者或评审挑出的漏洞」在决策出口之前就压制下去。"
        "更关键的是，质疑过程被完整记录为可读的自然语言，"
        "使得决策结论的理由链可被人类审视，而非黑箱输出。")

    # ── 创新点 2 ──
    R.h2("10.2 CMDB 资产风险的处置闭环")
    R.rich([("解决的问题：", {'bold': True}),
            ('现有安全工具大多止步于「发现漏洞」，'
             '输出的报告无法直接转化为工单，'
             '安全人员仍需手工整理「先修什么、怎么修、修完怎么确认」。', {})])
    R.rich([("创新做法：", {'bold': True}),
            ('对接企业 CMDB，将资产脆弱性判定直接转换为处置工单。'
             '每条工单包含七项内容：受影响版本区间、修复版本、官方补丁、'
             '临时缓解措施、变更窗口、回滚方案、可留痕的验收步骤。'
             '资产身份由 CI 编号、主机名、IP 与机房位置共同构成，'
             '使工单能直接回答「哪台机器、什么组件、放在哪个机房」。', {})])
    R.rich([("验收闭环：", {'bold': True}),
            ('每条工单附带四步验收动作，核心是「可执行、可留痕」——'
             '执行版本命令确认、核对厂商公告、扫描器重扫、'
             '在 CMDB 台账更新状态并回填实际修复日期。'
             '其中「核对厂商公告」针对的是台账人工填写可能有误这一真实问题。', {})])
    R.callout(
        "价值",
        "系统输出的是可执行的工单而非漏洞清单。"
        "实测表明，即使台账中约四分之一的记录没有公开漏洞编号，"
        "系统依然能基于组件与版本信息给出可执行的处置方案。")

    # ── 创新点 3 ──
    R.h2("10.3 引用可回溯、零编造的多跳问答")
    R.rich([("解决的问题：", {'bold': True}),
            ('大模型在安全问答中存在严重幻觉问题——'
             '会生成看似合理但不存在的漏洞编号，'
             '而安全人员若据此决策可能引入更大风险。', {})])
    R.rich([("创新做法：", {'bold': True}),
            ('采用「先检索后生成」策略，并对生成结果做机械校验：'
             '答案正文中出现的每个 CVE 编号必须来自实际引用集合，'
             '不满足则拒绝返回。同时强制每个论断附带引用编号，'
             '用户可点击直接打开漏洞详情页验证。', {})])
    R.rich([("多跳能力：", {'bold': True}),
            ('实现实体驱动的迭代式推理：从前一跳结果中抽取关键实体，'
             '作为下一跳的检索条件，直至答案充分。'
             '该能力覆盖九类问题形态，实测 %d 题全部通过。'
             % MH.get("total", 0), {})])
    R.callout(
        "价值",
        "实测问答五项深度指标全部达到 100%，正文编造数为 0。"
        "在安全场景下，「宁可不说」优于「说错」，"
        "系统把这一点落实为可验证的工程约束，而非仅靠提示词要求。")

    # ── 创新点 4 ──
